package w3schools.week3.Arrays;

public class Arrays {
	  public static void main(String[] args) {
	    String[] cars = {"Volvo", "BMW", "Ford", "Mazda"};
	    System.out.println(cars[0]);

	    // Change an element
	    cars[0] = "Opel";
	    System.out.println(cars[0]);
	    
	    // Length
	    System.out.println(cars.length);
	}
}
