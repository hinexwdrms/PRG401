package w3schools.week3.ForLoop;

public class ForEach {
	  public static void main(String[] args) {
		// Cars
	    String[] cars = {"Volvo", "BMW", "Ford", "Mazda"};
	    
	    for (String car : cars) {
	      System.out.println(car);
	    }
	    System.out.println();
	    	//Numbers
	    int[] numbers = {10, 20, 30, 40};

	    for (int num : numbers) {
	      System.out.println(num);
	    }
	  }
	}
