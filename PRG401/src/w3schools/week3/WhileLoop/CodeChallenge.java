package w3schools.week3.WhileLoop;

public class CodeChallenge {
	  public static void main(String[] args) {
	    // Declare and assign i
	    int i = 1;

	    // Write a while loop
	    while (i <= 5) {
	      // Inside the loop, print i
	      System.out.println(i);

	      // Increase i by 1
	      i++;
	    }
	  }
	}
