package w3schools.week2.Strings;

public class NumsAndStrings {
	public static void main(String[] args) {
		  int x = 10;
		  int y = 20;
		  int z = x + y;
		  System.out.println(z);
		  
		  
		 //Adding strings
		  String a = "10";
		  String b = "20";
		  String c = a + b;  // z will be 1020 (a String)
		  System.out.println(c);
		  
		  //Adding Number and Strings
		  String p = "10";
		  int q = 20;
		  String r = p + q;
		  System.out.println(r);
	}
}
	
