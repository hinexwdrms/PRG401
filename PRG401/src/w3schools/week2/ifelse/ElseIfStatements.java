package w3schools.week2.ifelse;

public class ElseIfStatements {
	  public static void main(String[] args) {
	    int time = 22;
	    
	    if (time < 12) {
	      System.out.println("Good morning.");
	    } else if (time < 18) {
	      System.out.println("Good day.");
	    } else {
	      System.out.println("Good evening.");
	    }
	  }
	}
